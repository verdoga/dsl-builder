// Package app координирует операции DSL-Builder по ТЗ 1.0; проект API v1.
// Здесь только состояние диалога и последовательности вызовов владельцев.
// console получает Snapshot, показывает его через preview и передаёт решения
// методам Operation. app не импортирует console/preview, не читает stdin,
// не печатает меню, не задаёт номера пунктов и не завершает процесс.
// Главное меню, версия из сборки и повтор вопросов принадлежат console/main.
//
// Создание: NewCreate → Analyze → Snapshot → правки → SetDestination →
// ReviewSave → ConfirmSave → Save. Обновление: NewUpdate → Analyze →
// отдельные DecideField и DecidePlacement → PrepareRevision → тот же цикл.
// Добавление: NewAdd → Analyze → исправление размещения → тот же цикл.
// Отказ от записи возвращает превью; отказ от правки сохраняет принятые данные.
// Cancel вызывается при возврате в главное меню, выходе и потере ввода;
// главное меню может создать новую Operation. Retry заново читает исходники.
//
// Все вызовы последовательны. Нулевую Operation использовать нельзя.
// Ни одно публичное API не принимает Module/State/Plan для замены внутреннего
// состояния. Возвращаемые снимки независимы; module.File неизменяем по контракту.
// Подтверждения привязаны к закрытым идентификаторам именно этой операции.
// Ни поправленный снаружи Snapshot, ни старый токен не разрешают запись.
// Предметные модели не дублируются; lesson/manifest/model используются через
// parsed.Input, module.File, module.Module и catalog, без новых прямых импортов.
