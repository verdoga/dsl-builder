// Package resourceusage учитывает ресурсы обрабатываемых исходников текущей операции.
// Область включает файлы resourceDirs, явно подключённые внешние файлы
// и их проверяемые сопутствующие файлы; её состав передаёт вызывающий код.
// Ресурсы прежних уроков архива автоматически в область не добавляются.
// Пакет не ищет, не читает, не встраивает файлы и не нормализует пути.
package resourceusage

// Registry хранит уникальные пути и факт успешного встраивания в текущей операции.
// Нулевое значение готово к работе; для новой операции или повторного анализа
// создаётся новый реестр. После первого изменения реестр не копируют по значению.
// Методы вызываются последовательно, без одновременного доступа.
// Входные пути непустые, полные и заранее нормализованные владельцем путей.
// Один файл должен иметь одну и ту же строку пути во всех входах операции,
// включая варианты регистра, разделителей и разрешённых файловых ссылок.
// Идентичность определяется точным равенством этих строк, а не именем файла.
type Registry struct {
	// files содержит все учтённые пути; true означает успешное встраивание,
	// false — отсутствие успешного встраивания, отсутствие ключа — вне реестра.
	files map[string]bool
}

// Register объединяет paths с областью учёта без отметки об использовании.
// Передаются все обнаруженные в области файлы, включая неподдерживаемые
// расширения; выбор области и проверку доступности выполняет вызывающий код.
// Повторы не увеличивают счётчики; прежняя отметка использования сохраняется.
// Пустой или nil-срез ничего не меняет; входной срез не сохраняется.
func (r *Registry) Register(paths []string) {
	if len(paths) == 0 {
		return
	}
	if r.files == nil {
		r.files = make(map[string]bool, len(paths))
	}
	for _, path := range paths {
		if _, exists := r.files[path]; !exists {
			r.files[path] = false
		}
	}
}

// MarkUsed отмечает paths после успешного включения содержимого файлов
// хотя бы в один урок текущей операции; одного выбора или чтения недостаточно.
// Подтверждение успешного встраивания передаёт вызывающий код.
// Ранее неизвестные пути одновременно добавляются в область учёта.
// Повторная отметка идемпотентна; неуспешные попытки сюда не передаются.
// Пустой или nil-срез ничего не меняет; входной срез не сохраняется.
func (r *Registry) MarkUsed(paths []string) {
	if len(paths) == 0 {
		return
	}
	if r.files == nil {
		r.files = make(map[string]bool, len(paths))
	}
	for _, path := range paths {
		r.files[path] = true
	}
}

// Merge объединяет реестры уроков одной операции без повторного счёта путей.
// Путь использован в результате, если использован хотя бы в одном реестре.
// other не изменяется; общая изменяемая память между реестрами не сохраняется.
// Объединение с собой или с nil ничего не меняет.
func (r *Registry) Merge(other *Registry) {
	if other == nil || other == r || len(other.files) == 0 {
		return
	}
	if r.files == nil {
		r.files = make(map[string]bool, len(other.files))
	}
	for path, used := range other.files {
		r.files[path] = r.files[path] || used
	}
}
