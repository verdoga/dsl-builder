// Package manifest описывает и проверяет фиксированный контракт Manifest 1.0.
// Проверки не изменяют значения, порядок массивов или дату формирования.
// catalog отвечает за размещение, смешанный состав, синтез, сортировку,
// числовые конфликты весов и одинаковые названия секций; module — за
// уникальность ID/имён файлов и соответствие записей файлам и метаданным.
// Допустимый схемой null order единственного урока не отменяет требования
// catalog получить итоговый вес по ТЗ. Проверка схемы не проверяет DSL.
// moduleio читает и декодирует JSON, вызывает ValidateShape до потери
// сведений о полях, затем Validate для модели; запись также принадлежит ему.
// Только Validate недостаточно для проверки произвольного входного JSON.
package manifest

// FormatVersion — единственная поддерживаемая версия формата манифеста.
const FormatVersion = "1.0"

// Manifest — корневой объект; все три поля обязательны и не допускают null.
type Manifest struct {
	// FormatVersion — версия формата, всегда строка 1.0.
	FormatVersion string `json:"formatVersion"`

	// CreatedAt — дата сборки в UTC; назначает вызывающий код при записи.
	CreatedAt string `json:"createdAt"`

	// Course — один курс в одной из двух форм схемы.
	Course Course `json:"course"`
}
