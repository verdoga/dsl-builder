// Package diagnostic представляет ошибки сборщика без обнаружения ошибок,
// чтения файлов, управления операцией и вывода в консоль.
// Профильный пакет заполняет данные; console выбирает оформление и действия.
// Диагностика входного контракта остаётся в parsed/model; её преобразование
// и отбор ошибок без предупреждений и рекомендаций выполняет parsed.
package diagnostic

// Error — единая структурированная ошибка сборщика, реализующая error.
// Создаётся профильным пакетом непосредственно через поля структуры.
// Несколько независимых ошибок передаются обычным срезом *Error.
type Error struct {
	// Code — обязательный стабильный машинный код, назначенный владельцем
	// проверки; рекомендуется имя пакета и точка перед локальным кодом.
	// Это код сборщика, а не копия типа model.Code входного контракта.
	Code string

	// Reason — обязательная понятная причина на русском языке.
	// Не подменяется стеком вызовов или необработанным текстом Cause.
	Reason string

	// Context — известные сведения о месте ошибки; неизвестные не выдумываются.
	Context Context

	// Related — все связанные места в порядке, заданном профильным пакетом.
	// Для конфликта содержит всех участников, для неоднозначного ресурса —
	// всех кандидатов; основной Context может указывать на исходный JSON.
	Related []Context

	// Details — дополнительные сведения для показа в заданном порядке:
	// исходный вес, признак ошибки парсера, его код и сообщение,
	// тип ресурса, подстрока поиска, каталоги поиска и прочие известные детали.
	Details []Detail

	// Cause — исходная техническая ошибка для стандартной цепочки error;
	// nil, если технической причины нет. Пользовательское описание — Reason.
	Cause error
}

// Error возвращает краткое описание из Code и Reason без побочных эффектов.
// Полный контекст и подробности доступны console через поля и errors.As.
func (e *Error) Error() string {
	return e.Code + ": " + e.Reason
}

// Unwrap возвращает Cause для errors.Is и errors.As; ничего не классифицирует.
func (e *Error) Unwrap() error {
	return e.Cause
}
