package diagnostic

// Detail — именованная подробность для показа без разбора текста причины.
// Позволяет профильным пакетам сообщать свои данные без зависимости
// diagnostic от моделей ресурсов, весов и входного контракта.
type Detail struct {
	// Label — понятное русское название подробности; повторения допустимы,
	// например для нескольких каталогов поиска или сообщений парсера.
	Label string

	// Value — точное строковое значение; пустая строка также значима.
	// Исходные веса, поисковые строки и сообщения не обрезаются,
	// не переводятся и не преобразуются в машинные числа.
	Value string
}
