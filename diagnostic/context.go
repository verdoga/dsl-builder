package diagnostic

// Context — место ошибки сборщика или связанного файла, а не диапазон DSL.
// Пустая строка и нулевой номер означают отсутствие известных сведений.
// Пути, ID и координаты передаются владельцем проверки без нормализации.
type Context struct {
	// Path — конкретный путь исходного JSON, ресурса, каталога или архива.
	// Для исходных ошибок это путь технического JSON, не document.filePath.
	Path string

	// FileName — техническое имя записи урока или манифеста внутри ZIP;
	// при известном архиве Path указывает на него, а не на вымышленный файл.
	FileName string

	// LessonID — ID урока в исходном написании без числового преобразования.
	LessonID string

	// PageID — полный ID страницы, если страница известна.
	PageID string

	// Line — номер физической строки с 1; при ошибке парсера — строка DSL.
	Line int

	// Column — колонка с 1 в кодовых точках Unicode, если известна строка;
	// 0 позволяет передать известную строку без выдуманной колонки.
	Column int
}
