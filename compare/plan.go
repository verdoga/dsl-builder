package compare

// Plan — предложения изменений одного урока для app, revision и preview.
// Индексы адресуют исходные неизменяемые снимки, начиная с нуля; они не ID.
// План не содержит новой модели или подтверждений. Его массивы и значения
// полей принадлежат результату и не разделяют изменяемую память со снимками.
type Plan struct {
	// Fields — независимые предложения изменения названия урока,
	// подзаголовка и названий страниц, в этом порядке, страницы по кандидату.
	// Каждое требует отдельного решения даже при ReplaceLesson.
	// Для PageTitle с OldPage=-1 прежнее поле не установлено: показ и отказ
	// определены FieldChange; старое название по позиции не подставляется.
	Fields []FieldChange

	// ReplaceLesson — требуется заменить все страницы и ноды урока;
	// ID урока и техническое имя сохраняет revision совместно с module.
	// При true Pages пуст: ложное соответствие старых и новых нод не строится.
	ReplaceLesson bool

	// Reasons — конкретные причины полной замены; непусты ровно при
	// ReplaceLesson. Неоднозначность — причина плана, а не ошибка данных.
	Reasons []Reason

	// Pages — изменения нод страниц с сохранённым соответствием по позиции,
	// по возрастанию индекса. Страница только с изменённым названием сюда
	// не включается. При ReplaceLesson список пуст.
	Pages []PageChange
}

// HasContentChanges сообщает о полной замене или непустом Pages.
// Не учитывает Fields, пока app не получит отдельные решения пользователя.
// При false и отсутствии принятых Fields урок не меняется; наличие изменений
// манифеста и необходимость записи всего модуля определяют другие пакеты.
func (plan *Plan) HasContentChanges() bool {
	return plan.ReplaceLesson || len(plan.Pages) > 0
}

// PageChange — точечные замены либо полная замена нод одной страницы.
// ID этой страницы сохраняется; новые номера и суффиксы определяет revision.
type PageChange struct {
	// Index — индекс страницы одновременно в старом уроке и кандидате.
	Index int

	// ReplaceNodes — все ноды страницы заменяются, включая вложенные;
	// тогда Nodes пуст и Reasons непуст. Старые и новые ID для превью
	// перечисляются отдельно, без вымышленного попарного соответствия.
	ReplaceNodes bool

	// Reasons — различия числа или вложенности нод с точными адресами;
	// при точечных заменах пусты. Процентные пороги не используются.
	Reasons []Reason

	// Nodes — только изменённые собственные поля при сохранённой структуре,
	// в порядке обхода: родитель, затем дети. При ReplaceNodes пуст.
	Nodes []NodeChange
}

// NodeChange — собственные изменения ноды на одной соответствующей позиции.
// Изменение потомка не включает родителя, если собственные поля равны.
type NodeChange struct {
	// Path — непустая цепочка индексов: корневая нода страницы, её ребёнок
	// и далее. Путь одинаков в обоих снимках, глубина не ограничивается.
	Path []int

	// Fields — непустой список изменённых собственных полей в порядке
	// type, flags, data; дочерние nodes и генерируемый id сюда не входят.
	Fields []NodeField
}

// NodeField — собственное поле ноды, влияющее на её замену.
type NodeField string

const (
	// NodeTypeChanged — изменился тип при сохранённой форме дерева.
	NodeTypeChanged NodeField = "type"
	// NodeFlagsChanged — изменилось значение либо присутствие флага.
	NodeFlagsChanged NodeField = "flags"
	// NodeDataChanged — изменились данные, их порядок, ответы или подсказки.
	NodeDataChanged NodeField = "data"
)
