package safewrite

import "io"

// WriteFunc записывает всё содержимое кандидата в переданный поток.
// Callback завершает и закрывает собственный форматный writer, например ZIP,
// и возвращает ошибку его закрытия; сам файл принадлежит safewrite.
// Поток нельзя закрывать, сохранять для дальнейшей записи или использовать
// асинхронно. Callback не изменяет цель, исходные JSON и ресурсы.
// В одном вызове Write callback вызывается не более одного раза.
type WriteFunc func(dst io.Writer) error

// VerifyFunc проверяет полностью закрытый файл по полному временному пути.
// Для модуля callback проверяет чтение ZIP и согласованность всего состава
// средствами владельца формата; safewrite эти проверки не воспроизводит.
// Callback только читает файл и закрывает все свои дескрипторы до возврата,
// в том числе при ошибке. nil означает полное успешное завершение проверки.
// Callback вызывается один раз только после успешной записи и закрытия.
type VerifyFunc func(path string) error
