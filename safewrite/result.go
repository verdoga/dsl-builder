package safewrite

// Result описывает фактическое файловое состояние после Write, в том числе
// при ошибке. Нужен для различения записанного результата и неудачи очистки,
// а также для восстановления без разбора текста пользовательских сообщений.
// Пути отражают последние известные места файлов на момент возврата;
// существование файлов после внешних изменений не гарантируется.
type Result struct {
	// TargetPath — переданный полный путь назначения.
	TargetPath string

	// Installed — проверенный кандидат успешно установлен по TargetPath.
	// Не означает отсутствие ошибок последующей очистки.
	Installed bool

	// OriginalPath — место сохранённого исходного файла: цель после сохранения
	// или успешного отката, резервное имя при незавершённой операции.
	// Пусто при первоначальном отсутствии цели или удалении ненужной резервы.
	OriginalPath string

	// TemporaryPath — оставшийся временный кандидат, полный или частичный.
	// Пусто после его удаления либо успешной установки по TargetPath.
	// Состояние его готовности объясняется возвращённой диагностикой.
	TemporaryPath string
}
