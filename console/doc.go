// Package console проектирует последовательный русский диалог DSL-Builder.
// Псевдокод API v2: без реализации, тел функций и тестов.
// Только стандартные потоки, числовые меню и Enter; без TUI, очистки экрана,
// управления курсором, зависимости от цвета или внешних программ.
// Предметные действия выполняет app, текст полного превью — preview.
// console не читает архивы/JSON/ресурсы, не сравнивает модели и не пишет ZIP.
// Все вызовы последовательны, а принятые модели и разрешения принадлежат app.
//
// Каждый экран операции использует один свежий app.Snapshot. После решения,
// отказа, правки, Retry или смены цели снимок и нумерация запрашиваются заново.
// Метода отметки просмотра в принятом app v1 нет: console не выдумывает его.
// Согласие на запись передаётся только после полного успешного вывода именно
// SavePreview.Snapshot и Destination, с полученным SavePreview.Token.
// Ошибка представления или потока исключает запись по непоказанному плану.
//
// Main передаёт стандартные потоки, явную базу, версию сборки и os.Args[1:].
// Run сам вызывает app.NewCreate/NewUpdate/NewAdd; Application и фабрики нет.
// Для ошибки до Run main использует PrintError и завершает процесс сам.
