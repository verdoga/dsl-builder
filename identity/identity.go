// Package identity проверяет и форматирует идентификаторы SmoothLingua.
// Проверки охватывают всю строку без обрезания пробелов и исправления входа.
// Номера и ревизии передаются десятичными строками произвольной длины:
// преобразование в int, uint64 или float64 не является частью контракта.
// Форматирование принимает непустые последовательности ASCII-цифр
// с положительным значением, допускает ведущие нули и выдаёт каноническую
// запись с минимальной шириной, установленной для соответствующей части ID.
// Пакет не выбирает номера, не ищет максимумы, не ведёт счётчики,
// не проверяет уникальность и не решает, когда менять ревизию урока.
// Принадлежность страниц и нод уроку проверяет вызывающий пакет,
// сравнивая разобранный Prefix с LessonKey ID содержащего урока.
// Полные проверенные ID страниц и нод и технические имена сравнивают
// точным равенством строк; суффикс версии является частью полного ID ноды.
// Одинаковый номер в разных префиксах не означает идентичность.
// Проверка наличия поля или null входного JSON принадлежит parsed.
// При ошибке функции возвращают нулевой результат и *diagnostic.Error:
// Code из этого пакета, русскую Reason и точное ошибочное значение в Details.
// Context остаётся пустым; вызывающий код дополняет известные путь, имя,
// ID и координаты. Успех обозначается nil вместо ошибки.
package identity

const (
	// CodeInvalidLessonID — нарушен синтаксис ID урока.
	CodeInvalidLessonID = "identity.invalid_lesson_id"

	// CodeInvalidPageID — нарушена полная запись ID страницы.
	CodeInvalidPageID = "identity.invalid_page_id"

	// CodeInvalidNodeID — нарушена полная запись ID ноды.
	CodeInvalidNodeID = "identity.invalid_node_id"

	// CodeInvalidFileName — нарушено техническое имя урока.
	CodeInvalidFileName = "identity.invalid_file_name"

	// CodeInvalidNumber — неверен переданный номер или суффикс ревизии.
	CodeInvalidNumber = "identity.invalid_number"
)
