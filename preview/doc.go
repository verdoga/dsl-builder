// Package preview формирует последовательные русские текстовые блоки по ТЗ 1.0,
// разделы 7–9, 12–14 и 16. Проект API v1, без реализации и тестов.
// Входы принадлежат вызывающему коду и не изменяются. Результат — текст UTF-8
// с переводами строк LF; пакет не читает ввод и файлы, не пишет в консоль,
// не создаёт меню, не получает подтверждений и не решает, разрешена ли запись.
// Блоки соединяет console; состояние операции и решения предоставляет app.
// Предметные проверки, сортировка, сравнение и назначение ID уже выполнены
// владельцами данных. Вызовы Validate, Export, Changes, Conflicts, Build,
// Refresh и расчёт ревизии внутри preview не выполняются.
// Все ID, имена, веса и числа выводятся полностью без нормализации,
// float64, машинных ограничений чисел метаданных и сокращения до диапазонов.
// Содержимое Node.Data, ответы, подсказки, Base64 и OriginalBytes не выводятся.
// До записи используются будущие формулировки; текст не удостоверяет успех.
// error обозначает только невозможность представить переданный набор:
// отсутствующий снимок, недоступный адрес либо несогласованный селектор.
// Это русская ошибка интеграции без дампа данных; при ней текст равен пустой
// строке. Предметная диагностика выводится console отдельно и не дублируется.
// Пустые списки поддерживаются явно; nil обязательного указателя даёт error.
