// Package module хранит состав одного модуля по ТЗ 1.0 и проверяет связи
// между его файлами и манифестом. Проект v1; вход преобразователя — JSON 1.0.
// JSON, ZIP и физические записи читает/пишет moduleio; здесь нет ввода-вывода.
// Проверки схем принадлежат lesson/manifest, размещение — catalog,
// синтаксис имён и ключи ID — identity. Сравнение и ревизии остаются снаружи.
// app хранит редактируемый catalog.State отдельно, вызывает catalog.Export
// и соединяет итоговый Manifest с файлами перед Validate. module не меняет
// даты, версии, веса, секции, порядок отображения или принятые названия.
package module

import "github.com/verdoga/dsl-builder/manifest"

// ManifestFileName — единственное имя манифеста в корне выходного ZIP.
const ManifestFileName = "manifest.json"

// Module — состав в памяти, а не сериализуемая структура одного JSON.
// Незавершённый кандидат допустим до Validate, но не подлежит записи.
type Module struct {
	// Manifest — итоговый либо прочитанный манифест существующего контракта.
	Manifest manifest.Manifest

	// Files — все файлы уроков; срез сохраняет повторы для их обнаружения.
	// Порядок не определяет размещение: его задаёт только Manifest.
	// File неизменяем; для кандидата app создаёт отдельный срез Files.
	Files []*File
}
