// Package textdata формирует только собственные текстовые данные ноды.
// Архитектурный источник arc.zip:Builder/textdata/doc.go имеет метапометку
// «Проект версии 1: Go-псевдокод без реализаций и тестов».
// Вход — проверенные model.Line и model.Element контракта 1.0;
// результат — существующие lesson.Data, без дополнительной выходной модели.
// Приоритет правил: ТЗ 10.2, 10.6–10.8, 10.9, 17.2 и 19.2,
// затем фиксированная Lesson.schema; DSL и golden поясняют семантику.
//
// Границы нод, экземпляры включений, порядок, принадлежность страницам
// и выделение самостоятельных инструкций определяют вызывающие пакеты.
// Здесь не строятся дерево и ID, не назначаются флаги, не читаются файлы,
// не разбирается исходный DSL и не формируются данные других упражнений.
// Исходный script обрабатывается как самостоятельный текстовый блок;
// файловая расшифровка в media.data принадлежит resourceembed.
//
// Входные строки не изменяются. Каждый вызов создаёт независимые данные,
// включая Role и Answers, даже при повторном включении одного фрагмента.
// Все созданные Data имеют Type=lesson.DataText, строковый Value,
// ненулевой Role, пустой ненулевой Answers и Hint, пустой при отсутствии связи.
// Отсутствие собственных данных означает пустой ненулевой срез, не null.
// Технические сведения остаются только во входе и диагностике.
// Полную проверку собранного урока вызывает convert через lesson.Validate;
// этот пакет не дублирует проверку схемы или предварительные проверки parsed.
