// Package filetree разрешает пути и перечисляет файловое дерево средствами
// стандартной библиотеки Go для Windows. Содержимое файлов не читается.
// Область поиска, семантику ресурсов и режим операции задаёт вызывающий пакет.
// Метаданные файлов не заменяют последующую проверку доступности при чтении.
package filetree

import "io/fs"

// Entry разделяет адрес обнаружения и идентичность существующего объекта.
// Это позволяет сохранить базу относительных путей и имя через ссылку,
// одновременно исключая повторный учёт одного объекта файловой системы.
type Entry struct {
	// Path — полный очищенный адрес обнаружения с исходным регистром имён;
	// ссылки в его компонентах не заменены адресами их целей.
	// Для JSON каталог этого пути является базой ресурсных путей.
	Path string

	// IdentityPath — полный очищенный путь после разрешения файловых ссылок,
	// закреплённый Resolver за данным объектом на время всей операции.
	// Это доступный файловый путь, а не хеш или непрозрачный идентификатор.
	// Именно эту строку без изменения передают Register и MarkUsed пакета
	// resourceusage; её можно показывать как полный путь в отчёте.
	IdentityPath string

	// Info — стандартные сведения о целевом объекте после разрешения ссылки.
	// Тип проверяют через IsDir и Mode; имя обращения берут из Path,
	// поскольку Info.Name может относиться к цели ссылки.
	Info fs.FileInfo
}
