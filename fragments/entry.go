// Package fragments разворачивает определения текущего технического документа
// Contract 1.0. Проект v1: только объявления API и контрактов, без реализации.
// Работает с проверенным parsed.Input, не читает TXT и не разбирает DSL заново.
// Не строит страницы, task/step или lesson.Node, не назначает ID и версии,
// не преобразует текст, ответы и ресурсы. Исходный Input остаётся неизменным.
package fragments

import "github.com/verdoga/dsl-builder/parsed/model"

// Entry — конкретное вхождение исходной строки после развёртывания.
// Обёртка необходима: физические номера повторяются у разных include,
// а действующая связь родителя и граница вставки отличаются от исходных.
// Идентичность вхождения задаёт адрес *Entry, а не Source.Number или ID DSL.
// Последовательности Entry следуют физическому порядку входа; Parent задаёт
// только связи исходных строк, а семантические task/step определяет structure.
// Entry не сериализуется в JSON урока; после Expand доступен только для чтения.
type Entry struct {
	// Source — независимая полная копия model.Line, включая вложенные срезы
	// и указатели. Number, ParentLine, NestingLevel, Raw, EOL, элементы и их
	// Value/Raw/Start/End остаются исходными, включая null и пустые строки.
	// У служебной границы вставки Source содержит строку самого include.
	Source model.Line

	// Parent — действующий родитель этого вхождения. У обычной строки это
	// соответствующая копия исходного parentLine, у корня документа — nil.
	// Прямое содержимое определения после включения ссылается на Entry include;
	// через него доступен внешний родитель. Не заменяет Source.ParentLine.
	Parent *Entry

	// Included — упорядоченная последовательность строк тела только для include;
	// для остальных строк nil. Ненулевой пустой срез обозначает пустую вставку.
	// Сам Entry include — невизуальная граница, не кандидат в lesson.Node.
	// Его содержимое размещается на уровне вставки с сохранением внешнего
	// активного task/step/variant; соседство для answer/hint через границу
	// не переносится. Внешний обход считает всю вставку одной конструкцией.
	// Вложенность Included задаёт области вставок, а не дерево нод урока.
	Included []*Entry
}
