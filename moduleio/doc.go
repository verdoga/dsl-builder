// Package moduleio читает и записывает плоский ZIP модуля SmoothLingua.
// Проект API v1, ТЗ 1.0: только стандартная библиотека и разрешённые пакеты
// module, lesson, manifest, identity, diagnostic; реализация отсутствует.
// Формат JSON проверяют владельцы моделей, согласованность — module.Validate.
// Пакет не назначает имена, ID, даты, версии, порядок или секции и не исправляет
// прочитанные данные. Дата манифеста уже подготовлена вызывающим кодом.
// Служебные пути и контексты не сериализуются в JSON.
//
// Read и Verify открывают архив только для чтения, не извлекают записи на диск
// и закрывают все свои дескрипторы до возврата, включая неуспешный возврат.
// Write получает поток временного файла от app; не открывает конечный путь,
// не выполняет Sync, переименование, замену, восстановление или удаление файлов.
// Владельцем потока и файловой транзакции остаётся safewrite через app.
// Прямой зависимости moduleio от safewrite нет.
//
// Все публичные операции возвращают пустой список ошибок только при полном
// успехе. app преобразует ненулевые *diagnostic.Error в []error и errors.Join
// для callbacks safewrite.WriteFunc и safewrite.VerifyFunc. Список ошибок
// не преобразуется в текст: сохраняются причины и структурированная диагностика.
// Только app определяет наличие изменений и получает подтверждение записи.
