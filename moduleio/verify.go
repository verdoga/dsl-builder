package moduleio

import "github.com/verdoga/dsl-builder/diagnostic"

// Verify проверяет закрытый временный архив полным вызовом Read(path),
// отбрасывает успешную модель и возвращает весь список ошибок без изменения.
// Проверяет имена и повторы записей, полное чтение/CRC каждого файла, UTF-8,
// JSON, схемы и согласованность module; одного чтения каталога ZIP недостаточно.
// Собственные дескрипторы закрыты до возврата, в том числе на Windows.
// Пустой список означает полностью корректный архив по поддерживаемым правилам;
// функция не устанавливает файл по целевому пути и не объявляет успех операции.
// app использует её в safewrite.VerifyFunc через errors.Join списка ошибок.
func Verify(path string) []*diagnostic.Error {
	_, problems := Read(path)
	return problems
}
